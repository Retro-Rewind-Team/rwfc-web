export type PixelIconName = keyof typeof ICONS;

/** Turns a bitmap into one SVG path, merging horizontal runs so the path stays short. */
export function bitmapToPath(rows: readonly string[]): string {
    let d = "";
    rows.forEach((row, y) => {
        let x = 0;
        while (x < row.length) {
            if (row[x] !== "#") {
                x++;
                continue;
            }
            const start = x;
            while (x < row.length && row[x] === "#") x++;
            d += `M${start} ${y}h${x - start}v1h-${x - start}z`;
        }
    });
    return d;
}

interface PixelIconProps {
    name: PixelIconName;
    size?: 16 | 32 | 64;
    class?: string;
}

export default function PixelIcon(props: PixelIconProps) {
    const [local] = splitProps(props, ["name", "size", "class"]);
    const path = createMemo(() => bitmapToPath(ICONS[local.name]));

    return (
        <svg
            width={local.size ?? 16}
            height={local.size ?? 16}
            viewBox="0 0 16 16"
            fill="currentColor"
            shape-rendering="crispEdges"
            aria-hidden="true"
            class={local.class}
        >
            <path d={path()} />
        </svg>
    );
}
